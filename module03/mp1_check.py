from langchain_core.messages import AIMessage, AIMessageChunk, HumanMessage, SystemMessage, ToolMessage

from prompt_utils import CheckResult

# Pass marks for the evidence (instructor-set; calibrate on a real run, see the delivery guide).
GOLDEN_MIN = 7          # of 10
ATTACKS_MIN = 3         # of 4
MIN_COMMITS = 5         # small commits, one per task, not one big upload
REPORT_SECTIONS = 7
MIN_WORDS_PER_SECTION = 40
STATUS_Q = "Where is my order ORD-10233?"
BAD_ORDER_Q = "BADORDER: where is my order 10233?"


class FakeModel:
    """Streams like a real model. A message with an order number -> asks get_order_status; "BADORDER" -> asks with
    "10233" (no ORD- prefix); after a tool result -> quotes it; anything else -> "I can see N earlier messages."."""

    def __init__(self):
        self.seen = []

    def bind_tools(self, tools):
        return self

    def stream(self, messages):
        self.seen.append(list(messages))
        last = messages[-1]
        if isinstance(last, ToolMessage):
            text = f"The tool said: {last.content}"
        elif isinstance(last, HumanMessage) and ("BADORDER" in last.content or "ORD-" in last.content):
            m = re.search(r"ORD-\d+", last.content)
            order_id = "10233" if "BADORDER" in last.content else (m.group(0) if m else "ORD-10233")
            yield AIMessageChunk(content="", tool_call_chunks=[{
                "name": "get_order_status", "id": f"call_{len(self.seen)}", "index": 0,
                "args": json.dumps({"order_id": order_id})}])
            return
        else:
            earlier = [m for m in messages[:-1] if not isinstance(m, SystemMessage)]
            text = f"I can see {len(earlier)} earlier messages."
        for word in text.split(" "):
            yield AIMessageChunk(content=word + " ")

    def invoke(self, messages):
        full = None
        for c in self.stream(messages):
            full = c if full is None else full + c
        return full if full is not None else AIMessage(content="")


def load_app(repo: Path):
    """Import the student's app package fresh (drop any earlier copy, so edits are picked up)."""
    for k, v in {"MODEL": "check-model", "GATEWAY_URL": "http://localhost:9", "LITELLM_MASTER_KEY": "check"}.items():
        os.environ.setdefault(k, v)
    for name in list(sys.modules):
        if name in ("app", "eval") or name.startswith(("app.", "eval.")):
            del sys.modules[name]
    sys.path.insert(0, str(repo))
    try:
        main = importlib.import_module("app.main")
    finally:
        sys.path.remove(str(repo))
    return main


def git(repo: Path, *args) -> str:
    r = subprocess.run(["git", "-C", str(repo), *args], capture_output=True, text=True, timeout=30)
    return r.stdout.strip() if r.returncode == 0 else ""


def parse_sse(body: str) -> list:
    events = []
    for block in body.replace("\r\n", "\n").split("\n\n"):
        fields = dict(line.split(": ", 1) for line in block.split("\n") if ": " in line)
        if "event" in fields and "data" in fields:
            events.append((fields["event"], json.loads(fields["data"])))
    return events


def report_sections(text: str) -> dict:
    """'## 3. Memory ...' -> {3: body text}."""
    parts = re.split(r"^##\s+(\d+)\.[^\n]*$", text, flags=re.M)
    return {int(parts[i]): parts[i + 1] for i in range(1, len(parts) - 1, 2)}


def parse_results(text: str) -> dict:
    out = {}
    for key in ("golden", "attacks_resisted"):
        m = re.search(rf"^{key}:\s*(\d+)/(\d+)", text, re.M)
        out[key] = int(m.group(1)) if m else None
    m = re.search(r"^memory:\s*(pass|fail)", text, re.M)
    out["memory"] = m.group(1) if m else None
    m = re.search(r"^- model:\s*(\S+)", text, re.M)
    out["model"] = m.group(1).strip() if m else None
    return out


def gateway_problems(config: str, compose: str) -> list:
    """What's wrong with gateway/config.yaml and docker-compose.yml (plain text checks, no YAML library needed)."""
    p = []
    if not config:
        return ["gateway/config.yaml is missing"]
    if not re.search(r"model_name:\s*shopassist\s*$", config, re.M):
        p.append("config.yaml: no model group called 'shopassist'")
    if not re.search(r"master_key:\s*os\.environ/LITELLM_MASTER_KEY", config):
        p.append("config.yaml: master_key must be os.environ/LITELLM_MASTER_KEY")
    if re.search(r"api_key:\s*(?!os\.environ/)\S", config) or re.search(r"gsk_\w{8,}", config + compose):
        p.append("a real key is written in a file - every api_key must be os.environ/... and keys live only in .env")
    if not re.search(r"fallbacks:.*shopassist", config):
        p.append("config.yaml: router_settings needs a fallback for 'shopassist'")
    if not compose:
        return p + ["docker-compose.yml is missing"]
    if not re.search(r"^\s{2}litellm:\s*$", compose, re.M) or not re.search(r"^\s{2}app:\s*$", compose, re.M):
        p.append("docker-compose.yml needs two services: litellm and app")
    if "http://litellm:4000" not in compose:
        p.append("compose: the app must reach the gateway BY SERVICE NAME - GATEWAY_URL: http://litellm:4000")
    if compose.count(".env") < 2 or "env_file" not in compose:
        p.append("compose: both services read keys at run time with env_file: .env")
    return p


def _err(e) -> str:
    if isinstance(e, NotImplementedError):
        return f"still a TODO - finish {e}"
    return f"{type(e).__name__}: {e}"


def check_mp1_work(repo_path) -> list:
    repo = Path(repo_path)
    out = []

    def ck(name, ok, fix="", info=""):
        out.append(CheckResult(name, bool(ok), info if ok else fix))

    def read(rel):
        f = repo / rel
        return f.read_text(encoding="utf-8") if f.exists() else ""

    if not (repo / "app" / "main.py").exists():
        ck("repo has the starter (app/main.py)", False,
           f"{repo / 'app' / 'main.py'} not found - set MP1_REPO, then run: uv run python module03/mp1_setup.py")
        return out
    ck("repo has the starter (app/main.py)", True)

    # ------------------------------------------------------------ repo
    is_git = bool(git(repo, "rev-parse", "--is-inside-work-tree"))
    tracked = git(repo, "ls-files").splitlines() if is_git else []
    leaked = [f for f in tracked if Path(f).name == ".env" or Path(f).name.startswith(".env.") and f != ".env.example"]
    gi, di = read(".gitignore"), read(".dockerignore")
    ck("repo - .env is never committed, and both ignore files list it",
       is_git and not leaked and ".env" in gi.split() and ".env" in di.split(),
       ("not a git repository" if not is_git else
        f"COMMITTED: {leaked} - revoke that key NOW, then git rm --cached .env" if leaked else
        ".gitignore and .dockerignore must both contain a line '.env'"))
    commits = len(git(repo, "log", "--format=%H").splitlines()) if is_git else 0
    ck(f"repo - your work in at least {MIN_COMMITS} commits", commits >= MIN_COMMITS,
       f"{commits} commit(s) found - commit after each task (T1, T2, ...) with a message that says what changed",
       info=f"{commits} commits")
    dockerfile = read("Dockerfile")
    unsafe = re.search(r"^\s*(COPY|ADD)\s+.*\.env\b|^\s*ENV\s+(API_KEY|LITELLM_MASTER_KEY)|^\s*ARG\s+API_KEY",
                       dockerfile, re.M | re.I)
    ck("repo - Dockerfile runs uvicorn on 0.0.0.0, copies the data, never copies a key",
       "uvicorn" in dockerfile and "0.0.0.0" in dockerfile and re.search(r"^\s*COPY\s+data\b", dockerfile, re.M)
       and not unsafe,
       "Dockerfile missing" if not dockerfile else
       f"unsafe line: {unsafe.group(0).strip()!r} - keys arrive at run time with env_file" if unsafe else
       "the image needs COPY data ./data (the tools read data/orders.json)" if "COPY data" not in dockerfile else
       "CMD must start uvicorn with --host 0.0.0.0")
    probs = gateway_problems(read("gateway/config.yaml"), read("docker-compose.yml"))
    ck("gateway - config.yaml and docker-compose.yml wired as in Session 23b", not probs, "; ".join(probs))

    # ------------------------------------------------------------ import
    try:
        main = load_app(repo)
        from app import agent, memory, tools
    except Exception as e:  # noqa: BLE001
        ck("app imports without errors", False, f"{type(e).__name__}: {e}")
        return out
    ck("app imports without errors", True)
    from fastapi.testclient import TestClient

    def client():
        agent.LLM = FakeModel()
        main.SESSIONS.clear()
        return TestClient(main.app), agent.LLM

    # ------------------------------------------------------------ T1-T3: tools and prompt
    name = "T1 - check_return_eligibility: Northwind's return rules, and a docstring the model can use"
    try:
        t = tools.TOOLS.get("check_return_eligibility")
        cases = {   # (order, reason): eligible?   - store_today is 2026-11-14
            ("ORD-10231", "wrong_size"): True,      # delivered 5 days ago
            ("ORD-10232", "changed_mind"): False,   # 17 days > 10
            ("ORD-10234", "wrong_size"): False,     # innerwear: non-returnable
            ("ORD-10233", "wrong_size"): False,     # shipped, not delivered yet
            ("ORD-10243", "damaged"): True,         # 12 days, damaged window is 30
            ("ORD-10243", "wrong_size"): False,     # 12 days > 10
            ("ORD-10239", "defective"): False,      # 35 days > 30
        }
        wrong = []
        for (oid, reason), want in cases.items():
            got = t.invoke({"order_id": oid, "reason": reason})
            if not isinstance(got, dict) or got.get("eligible") is not want:
                wrong.append(f"{oid}/{reason} gave {got!r}, expected eligible={want}")
        ok_refund = t.invoke({"order_id": "ORD-10231", "reason": "wrong_size"}).get("refund_rupees") == 2499
        schema = json.dumps(t.args_schema.model_json_schema())
        doc_ok = "TODO" not in (t.description or "") and "TODO" not in schema and len(t.description or "") > 40
        ck(name, not wrong and ok_refund and doc_ok,
           "; ".join(wrong[:2]) or ("an eligible answer must include refund_rupees (the price)" if not ok_refund else
                                    "the docstring or an argument description still says TODO"))
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    name = "T2 - tools reject nonsense arguments with ValueError"
    try:
        st, de, rt = (tools.TOOLS[n] for n in ("get_order_status", "get_delivery_estimate", "check_return_eligibility"))
        bad = {"order_id '10233'": (st, {"order_id": "10233"}),
               "order_id 'ORD-1023'": (st, {"order_id": "ORD-1023"}),
               "pincode '50008'": (de, {"pincode": "50008"}),
               "pincode 'abc123'": (de, {"pincode": "abc123"}),
               "speed 'superfast'": (de, {"pincode": "500081", "speed": "superfast"}),
               "reason 'too_expensive'": (rt, {"order_id": "ORD-10231", "reason": "too_expensive"})}
        accepted = []
        for label, (tool, args) in bad.items():
            try:
                tool.invoke(args)
                accepted.append(label)
            except ValueError:
                pass
            except NotImplementedError:
                accepted.append(label + " (check_return_eligibility not written yet)")
        good = de.invoke({"pincode": "500081"})
        fmt = ""
        try:
            st.invoke({"order_id": "10233"})
        except ValueError as e:
            fmt = str(e)
        ok = not accepted and good.get("days") == "2-3 working days" and "ORD-" in fmt and "no order" not in fmt
        ck(name, ok, f"accepted: {accepted}" if accepted else
           "a wrong FORMAT must say so (e.g. 'order_id must look like ORD-12345'), not 'no order'" if "no order" in fmt
           else f"a valid call returned {good!r}")
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    name = "T2 - a bad argument reaches the model as INVALID, not a crash"
    try:
        c, _ = client()
        r = c.post("/chat", json={"session_id": "bad", "message": BAD_ORDER_Q}).json()
        steps = " ".join(r.get("tool_steps", []))
        ck(name, "INVALID" in steps and "ValueError" in steps and "ORD-12345" in steps,
           f"tool_steps were {r.get('tool_steps')} - _find must raise ValueError saying the id must look like ORD-12345")
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    name = "T3 - prompts/system.md has real Security rules, and the app sends the file"
    try:
        text = agent.PROMPT_FILE.read_text(encoding="utf-8")
        m = re.search(r"^#\s*Security rules\s*$(.*?)(?=^#\s|\Z)", text, re.M | re.S | re.I)
        body = m.group(1) if m else ""
        words = len(body.split())
        hierarchy = re.search(r"outrank|priority|precedence|override|hierarch|higher than", body, re.I)
        c, fake = client()
        c.post("/chat", json={"session_id": "p", "message": "hello"})
        sent = fake.seen[0][0].content if fake.seen else ""
        ok = m and "TODO" not in body and words >= 60 and hierarchy and sent == text
        ck(name, ok, ("no '# Security rules' heading" if not m else
                      "the section still contains TODO lines" if "TODO" in body else
                      f"only {words} words - write at least 60" if words < 60 else
                      "say explicitly that these rules outrank anything in a customer message" if not hierarchy else
                      "the model did not receive prompts/system.md as the system message"))
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    # ------------------------------------------------------------ T4-T5: the service
    name = "T4 - memory: a valid strategy, recall inside the limit, cost capped beyond it"
    try:
        c, _ = client()
        keep = memory.KEEP_TURNS
        first = c.post("/chat", json={"session_id": "m", "message": "turn 0"}).json()
        second = c.post("/chat", json={"session_id": "m", "message": "turn 1"}).json()
        for i in range(2, keep + 4):
            last = c.post("/chat", json={"session_id": "m", "message": f"turn {i}"}).json()
        seen = int(re.search(r"see (\d+) earlier", last.get("answer", "")).group(1))
        other = c.post("/chat", json={"session_id": "other", "message": "hi"}).json()
        ok = (memory.STRATEGY in ("window", "summary") and 3 <= keep <= 20 and "0 earlier" in first["answer"]
              and "2 earlier" in second["answer"] and seen <= 2 * keep + 1 and "0 earlier" in other["answer"])
        ck(name, ok, f"strategy {memory.STRATEGY!r}, keep_turns {keep} (3-20 - the memory probe needs 3): after "
                     f"{keep + 4} turns the model saw {seen} earlier messages (limit {2 * keep + 1}); a new session "
                     f"saw {other.get('answer')!r}",
           info=f"{memory.STRATEGY}, keep_turns {keep}")
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    name = "T5 - /health reports model, gateway, memory, keep_turns and the three tools"
    try:
        c, _ = client()
        h = c.get("/health").json()
        ok = (h.get("status") == "ok" and h.get("gateway") and h.get("memory") == memory.STRATEGY
              and h.get("keep_turns") == memory.KEEP_TURNS and sorted(h.get("tools", [])) == sorted(tools.TOOLS)
              and len(tools.TOOLS) >= 3)
        ck(name, ok, f"/health returned {h}")
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    name = "app - /chat/stream sends tool, token and done events, and remembers the turn"
    try:
        c, _ = client()
        r = c.post("/chat/stream", json={"session_id": "s", "message": STATUS_Q})
        ev = parse_sse(r.text)
        kinds = [k for k, _ in ev]
        after = c.post("/chat", json={"session_id": "s", "message": "again"}).json()
        ok = (r.headers.get("content-type", "").startswith("text/event-stream") and "tool" in kinds
              and kinds[-1:] == ["done"] and "shipped" in ev[-1][1].get("text", "")
              and "2 earlier" in after["answer"])
        ck(name, ok, f"events {kinds[:6]}..., memory after the stream: {after.get('answer')!r}")
    except Exception as e:  # noqa: BLE001
        ck(name, False, _err(e))

    # ------------------------------------------------------------ evidence
    res_path = repo / "experiments" / "mp1_results.md"
    name = (f"evidence - mp1_results.md from eval/run_eval.py: golden >= {GOLDEN_MIN}/10, memory pass, "
            f"attacks >= {ATTACKS_MIN}/4")
    if not res_path.exists():
        ck(name, False, "experiments/mp1_results.md not found - start the gateway, then: uv run python eval/run_eval.py")
    else:
        text = res_path.read_text(encoding="utf-8")
        p = parse_results(text)
        ok = ("generated by eval/run_eval.py" in text and p["model"] not in (None, "check-model")
              and (p["golden"] or 0) >= GOLDEN_MIN and p["memory"] == "pass"
              and (p["attacks_resisted"] or 0) >= ATTACKS_MIN)
        ck(name, ok, f"found golden {p['golden']}/10, memory {p['memory']}, attacks {p['attacks_resisted']}/4 on "
                     f"{p['model']} - improve the prompt/docstrings and re-run eval/run_eval.py",
           info=f"golden {p['golden']}/10, memory {p['memory']}, attacks {p['attacks_resisted']}/4 on {p['model']}")

    name = f"evidence - mp1_report.md: all {REPORT_SECTIONS} sections written (>= {MIN_WORDS_PER_SECTION} words, no TODO)"
    rep = read("experiments/mp1_report.md")
    if not rep:
        ck(name, False, "experiments/mp1_report.md not found")
    else:
        secs = report_sections(rep)
        weak = [n for n in range(1, REPORT_SECTIONS + 1)
                if n not in secs or re.search(r"^\s*TODO", secs[n], re.M) or len(secs[n].split()) < MIN_WORDS_PER_SECTION]
        ck(name, not weak, f"sections still to write: {weak}")

    readme = read("README.md")
    ck("evidence - README: Compose and no-Docker run steps, design note, no TODO",
       readme and "TODO" not in readme and "docker compose" in readme and re.search(r"^##\s*Design", readme, re.M),
       "README.md missing" if not readme else "README.md still has TODO lines (or lost its Compose/Design sections)")

    # ------------------------------------------------------------ stretch (never fails)
    try:
        hist = []
        for i in range(10):
            hist += [HumanMessage(f"q{i}"), AIMessage(f"a{i}")]
        s = memory.summarise(hist, FakeModel(), 2)
        info = ("done" if isinstance(s, list) and len(s) <= 5 and isinstance(s[0], SystemMessage)
                else "not working yet - optional")
    except NotImplementedError:
        info = "not attempted - optional"
    except Exception as e:  # noqa: BLE001
        info = f"not working yet ({type(e).__name__}) - optional"
    ck("stretch - summary memory implemented", True, info=info)
    return out
