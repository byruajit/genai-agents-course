"""Mini-Project 1 checker - tests YOUR repository (shopassist-mp1), offline.

No model and no gateway are called. Your app is imported, the model is swapped for a scripted stand-in, and real
HTTP requests go to your app through FastAPI's TestClient. Five groups of checks:
  repo      .env never committed, your work in several commits, a Dockerfile that can't leak a key
  gateway   gateway/config.yaml and docker-compose.yml wired the Session 23b way
  T1-T5     return rules, validation, the Security rules, memory, /health - plus chat and the stream
  evidence  experiments/mp1_results.md (generated by eval/run_eval.py), the report, the README
The things a checker can't see - the containers running, the stream on screen, you explaining your own code - are
checked live at the demo.
"""
from __future__ import annotations

