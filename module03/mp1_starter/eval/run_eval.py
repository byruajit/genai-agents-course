"""Run the Mini-Project 1 evidence set against YOUR app, with the REAL model, and write the results file.

From the repo root (with your .env present):
    uv run python eval/run_eval.py
It writes experiments/mp1_results.md. Don't edit that file by hand: re-run this script instead. The checker
reads it, and your report (experiments/mp1_report.md) discusses it.

It uses FastAPI's TestClient, so your APP doesn't need to be running - but the GATEWAY does (the app reaches the
model only through it):  docker compose up -d litellm     (or Path B in the README, without Docker).
It sends 10 + 4 + 4 = 18 requests: roughly 15,000-30,000 tokens on Groq.
"""
import re
import sys
import time
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from app import main  # noqa: E402
from eval.cases import ATTACKS, GOLDEN, MEMORY  # noqa: E402

OUT = ROOT / "experiments" / "mp1_results.md"


def norm(text: str) -> str:
    return text.lower().replace(",", "").replace(" ", "").replace("₹", "")


def text_ok(answer: str, any_of: list, none_of: list = (), all_of: list = ()) -> bool:
    a = norm(answer)
    return (all(norm(x) in a for x in all_of) and (not any_of or any(norm(x) in a for x in any_of))
            and not any(norm(x) in a for x in none_of))


def tools_used(steps: list) -> list:
    return sorted({s.split("(", 1)[0] for s in steps})


def tools_ok(used: list, expected: list) -> bool:
    """Every expected tool was used (checking the status first is fine); no tool at all when none is expected."""
    return set(expected) <= set(used) if expected else not used


def ask(client, session_id: str, message: str) -> dict:
    t = time.time()
    r = client.post("/chat", json={"session_id": session_id, "message": message})
    r.raise_for_status()
    body = r.json()
    body["seconds"] = round(time.time() - t, 1)
    return body


def short(text: str, n: int = 90) -> str:
    return text.replace("\n", " ").replace("|", "/")[:n]


def main_() -> None:
    client = TestClient(main.app)
    health = client.get("/health").json()
    print(f"model group {health.get('model')} via the gateway at {health.get('gateway')}")
    lines = ["# Mini-Project 1 - results", "",
             "<!-- generated by eval/run_eval.py - do not edit by hand; re-run it instead -->", "",
             f"- date: {date.today().isoformat()}", f"- model: {health.get('model')} (gateway {health.get('gateway')})",
             f"- memory: {health.get('memory', '?')} (keep_turns {health.get('keep_turns', '?')})", ""]

    print("golden set ...")
    rows, g_pass, t_pass = [], 0, 0
    for item in GOLDEN:
        res = ask(client, f"golden-{item['id']}", item["question"])
        used = tools_used(res["tool_steps"])
        tool_ok = tools_ok(used, item["expect_tools"])
        ans_ok = text_ok(res["answer"], item["answer_any"], item["answer_not"], item.get("answer_all", []))
        g_pass += tool_ok and ans_ok
        t_pass += tool_ok
        rows.append(f"| {item['id']} | {', '.join(item['expect_tools']) or '-'} | {', '.join(used) or '-'} | "
                    f"{'yes' if tool_ok else 'NO'} | {'yes' if ans_ok else 'NO'} | {res['seconds']} | "
                    f"{short(res['answer'])} |")
        print(f"  {item['id']}: tool {'ok' if tool_ok else 'WRONG'}, answer {'ok' if ans_ok else 'WRONG'}")
    lines += ["## Golden set (10)", "",
              "| id | expected tools | used | right tools | right answer | s | answer (start) |",
              "|---|---|---|---|---|---|---|", *rows, ""]

    print("memory probe ...")
    rows, m_ok = [], True
    for i, turn in enumerate(MEMORY["turns"], 1):
        res = ask(client, "memory-m1", turn["message"])
        ok = text_ok(res["answer"], turn["answer_any"])
        if "expect_tools" in turn:
            ok = ok and tools_ok(tools_used(res["tool_steps"]), turn["expect_tools"])
        m_ok = m_ok and ok
        rows.append(f"| {i} | {short(turn['message'], 60)} | {'yes' if ok else 'NO'} | {short(res['answer'])} |")
    lines += ["## Memory probe (one conversation, 4 turns)", "", "| turn | customer | ok | answer (start) |",
              "|---|---|---|---|", *rows, ""]

    print("attacks ...")
    rows, a_pass = [], 0
    for atk in ATTACKS:
        res = ask(client, f"attack-{atk['id']}", atk["message"])
        broken = [p for p in atk["broken_if"] if re.search(p, res["answer"], re.I)]
        missing = atk["must"] and not re.search(atk["must"], res["answer"].replace(" ", ""), re.I)
        resisted = not broken and not missing
        a_pass += resisted
        why = "" if resisted else ("matched " + broken[0] if broken else "correct answer missing")
        rows.append(f"| {atk['id']} | {atk['family']} | {'yes' if resisted else 'NO'} | {why} | "
                    f"{short(res['answer'])} |")
        print(f"  {atk['id']} {atk['family']}: {'resisted' if resisted else 'BROKEN'}")
    lines += ["## Attacks (4)", "", "| id | family | resisted | why not | answer (start) |", "|---|---|---|---|---|",
              *rows, ""]

    summary = ["## Summary", "", f"golden: {g_pass}/10", f"golden_right_tools: {t_pass}/10",
               f"memory: {'pass' if m_ok else 'fail'}", f"attacks_resisted: {a_pass}/4", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines[:8] + summary + lines[8:]), encoding="utf-8")
    print("\n".join(summary))
    print("written:", OUT)


if __name__ == "__main__":
    main_()
